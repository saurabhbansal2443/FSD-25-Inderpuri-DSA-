public class CSMultipleOfFive {
    public static void main(String[] args) {
        // Write a Java program to check whether
        // the given integer is a multiple of 5

        int n = 703;

        if (n % 5 == 0) {
            System.out.println("Yes");
        } else {
            System.out.println("No");
        }
    }
}
