import java.util.*;

public class CSPositiveNegativeZero {
    public static void main(String[] args) {

        // Write a porgram to find weather a number is positive negative or zero

        // 10 --> positive
        // -3 --> Negative
        // 0 --> zero

        int n = 10;

        if (n > 0) {
            System.out.println("Positive");
        } else if (n < 0) {
            System.out.println("Negative");
        } else {
            System.out.println("Zero");
        }
    }
}
